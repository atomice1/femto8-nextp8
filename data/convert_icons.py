#!/usr/bin/env python3
"""
Convert tool_icons.png to C bitmap data for p8_editor_sprite.c.

The PNG contains 8 icons (16x16 each) laid out horizontally.
We need the first 7 icons, cropped to the top 16x8 pixels.
Non-white pixels are transparent; white pixels are opaque.
Each pixel becomes 1 bit (1=opaque, 0=transparent).
"""

from PIL import Image
import sys

def convert_icon_to_bits(img, icon_idx):
    """Extract one icon (16x8) and convert to bit array.
    
    The icon is 16 pixels wide and 8 pixels tall.
    Each row stores 16 bits, MSB=leftmost pixel.
    """
    # Each icon is 16 pixels wide, starting at icon_idx * 16
    left = icon_idx * 16
    top = 0
    right = left + 16
    bottom = 8  # Only top 8 pixels

    icon = img.crop((left, top, right, bottom))

    # Convert to bits: 1 = white (opaque), 0 = non-white (transparent)
    bits = []
    for y in range(8):
        row_bits = 0
        for x in range(16):
            pixel = icon.getpixel((x, y))
            # Check if pixel is white (all channels >= 200 for tolerance)
            if isinstance(pixel, int):
                is_white = pixel >= 200
            else:
                is_white = pixel[0] >= 200 and pixel[1] >= 200 and pixel[2] >= 200

            row_bits = (row_bits << 1) | (1 if is_white else 0)
        bits.append(row_bits)

    return bits

def main():
    png_path = "data/tool_icons.png"
    output_h = "src/data/tool_icons.h"
    
    print(f"Reading: {png_path}")
    img = Image.open(png_path)
    
    if img.width != 128 or img.height != 16:
        print(f"Warning: Expected 128x16, got {img.width}x{img.height}")
    
    # Convert first 8 icons
    all_bits = []
    for i in range(8):
        bits = convert_icon_to_bits(img, i)
        all_bits.append(bits)
        print(f"Icon {i}: {bits}")
    
    # Generate C header code
    c_code = '''/**
 * Tool palette bitmap data for sprite editor.
 * Generated by convert_icons.py from tool_icons.png
 * Format: 8 icons, each 16x8 pixels, stored as 8 rows of 16-bit values.
 * Bit 1 = opaque pixel, Bit 0 = transparent.
 */

#ifndef TOOL_ICONS_H
#define TOOL_ICONS_H

#include <stdint.h>

static const uint16_t tool_icon_data[8][8] = {
'''
    
    icon_names = ['PENCIL', 'FILL', 'SELECT', 'PAN', 'LINE', 'RECT', 'OVAL', 'FILLRECT']
    
    for i, bits in enumerate(all_bits):
        c_code += f'    /* {icon_names[i]} */\n'
        c_code += '    {\n'
        for row in range(8):
            c_code += f'        0x{bits[row]:04X},\n'
        c_code += '    },\n'
    
    c_code += '''};'''

    c_code += '''

#endif // TOOL_ICONS_H
'''

    # Write header file
    with open(output_h, 'w') as f:
        f.write(c_code)
    
    print(f"\nGenerated: {output_h}")
    
    # Also print the data in a format suitable for direct insertion
    print("\n--- C code ready for insertion ---")
    print(c_code)

if __name__ == "__main__":
    main()
